func TestRuleStoreMatchAndSave(t *testing.T) {
	tempDir, err := os.MkdirTemp("", "rule_test_*")
	if err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(tempDir)

	store := NewRuleStore(tempDir)

	rule1 := &MockRule{
		Name:       "Mock User Info",
		Enabled:    true,
		Method:     "GET",
		URLPattern: "/api/v1/user",
		Action:     "mock",
		MockStatus: 200,
		MockBody:   `{"id": 1, "name": "Test User"}`,
	}
	saved := store.Save(rule1)
	if saved.ID == "" {
		t.Fatal("expected generated rule ID")
	}

	match := store.Match("GET", "https://example.com/api/v1/user?id=123")
	if match == nil || match.Name != "Mock User Info" {
		t.Fatalf("expected rule match, got: %v", match)
	}

	postMatch := store.Match("POST", "https://example.com/api/v1/user")
	if postMatch != nil {
		t.Errorf("expected no match for POST")
	}
}

func TestProxyAddonMockAndRewrite(t *testing.T) {
	tempDir, err := os.MkdirTemp("", "proxy_server_test_*")
	if err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(tempDir)

	srv, err := NewServer(Config{
		Port:       9898,
		StorageDir: tempDir,
		MaxHistory: 100,
	})
	if err != nil {
		t.Fatalf("failed to create proxy server: %v", err)
	}

	// Add a mock rule
	srv.Rules().Save(&MockRule{
		Name:       "Test Mock Endpoint",
		Enabled:    true,
		Method:     "GET",
		URLPattern: "example.org/test-mock",
		Action:     "mock",
		MockStatus: 200,
		MockBody:   `{"mocked": true, "status": "ok"}`,
	})

	addon := &proxyAddon{server: srv}

	parsedURL, _ := url.Parse("http://example.org/test-mock")
	flow := &mitmproxy.Flow{
		Request: &mitmproxy.Request{
			Method: "GET",
			URL:    parsedURL,
			Header: make(http.Header),
		},
	}

	// Run Request hook (Mock)
	addon.Request(flow)

	if flow.Response == nil {
		t.Fatal("expected flow.Response to be generated by mock rule")
	}
	if flow.Response.StatusCode != 200 {
		t.Errorf("expected 200, got %d", flow.Response.StatusCode)
	}
	if !strings.Contains(string(flow.Response.Body), `"mocked": true`) {
		t.Errorf("unexpected body: %s", string(flow.Response.Body))
	}
	if flow.Response.Header.Get("X-Mocked-By") != "ADB-Tool-Proxy" {
		t.Errorf("expected X-Mocked-By header")
	}

	// Verify session was recorded
	sessions := srv.Sessions().GetAll("", 10)
	if len(sessions) == 0 {
		t.Fatal("expected at least 1 session recorded")
	}
	if !sessions[0].IsMocked {
		t.Errorf("expected session.IsMocked to be true")
	}

	// Test mitm.it intercept
	mitmURL, _ := url.Parse("http://mitm.it/")
	mitmFlow := &mitmproxy.Flow{
		Request: &mitmproxy.Request{
			Method: "GET",
			URL:    mitmURL,
			Header: make(http.Header),
		},
	}
	addon.Requestheaders(mitmFlow)
	if mitmFlow.Response == nil {
		t.Fatal("expected mitm.it landing response")
	}
	if !strings.Contains(string(mitmFlow.Response.Body), "ADB Tool Proxy CA") {
		t.Errorf("expected landing page content, got %s", string(mitmFlow.Response.Body))
	}
}
